-- Schema snapshot for the fictional company demo. Deploy via Supabase migrations.
CREATE TABLE public.mock_companies (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_name text NOT NULL CHECK (length(trim(company_name)) BETWEEN 1 AND 160),
 risk_factor integer NOT NULL CHECK (risk_factor BETWEEN 0 AND 100),
 decided_disbursement_cents bigint NOT NULL CHECK (decided_disbursement_cents >= 0 AND decided_disbursement_cents <= money_requested_cents),
 money_requested_cents bigint NOT NULL CHECK (money_requested_cents BETWEEN 1 AND 10000000000),
 debtor text NOT NULL CHECK (length(trim(debtor)) BETWEEN 1 AND 160),
 from_date date NOT NULL,
 invoice_due date NOT NULL CHECK (invoice_due > from_date),
 pool text GENERATED ALWAYS AS (CASE WHEN risk_factor < 20 THEN 'Decline' WHEN risk_factor < 50 THEN 'Risky' WHEN risk_factor < 70 THEN 'Medium' ELSE 'Safe' END) STORED,
 source text NOT NULL CHECK (source IN ('seed', 'application')),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX mock_companies_pool ON public.mock_companies(pool);
ALTER TABLE public.mock_companies ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.mock_companies FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.mock_companies TO anon;
GRANT USAGE ON SEQUENCE public.mock_companies_id_seq TO anon;
GRANT ALL ON public.mock_companies TO service_role;
-- A separate random backend credential scopes access to this table, without a service-role key.
-- Replace FLOW_API_KEY_SHA256 with the SHA-256 hash of FLOW_SUPABASE_API_KEY.
CREATE POLICY flow_backend_select ON public.mock_companies FOR SELECT TO anon
 USING (encode(sha256(convert_to(coalesce(current_setting('request.headers', true)::jsonb ->> 'x-flow-api-key', ''), 'UTF8')), 'hex') = 'FLOW_API_KEY_SHA256');
CREATE POLICY flow_backend_insert ON public.mock_companies FOR INSERT TO anon
 WITH CHECK (encode(sha256(convert_to(coalesce(current_setting('request.headers', true)::jsonb ->> 'x-flow-api-key', ''), 'UTF8')), 'hex') = 'FLOW_API_KEY_SHA256' AND source = 'application' AND risk_factor BETWEEN 35 AND 90);
CREATE POLICY flow_backend_update ON public.mock_companies FOR UPDATE TO anon
 USING (encode(sha256(convert_to(coalesce(current_setting('request.headers', true)::jsonb ->> 'x-flow-api-key', ''), 'UTF8')), 'hex') = 'FLOW_API_KEY_SHA256')
 WITH CHECK (encode(sha256(convert_to(coalesce(current_setting('request.headers', true)::jsonb ->> 'x-flow-api-key', ''), 'UTF8')), 'hex') = 'FLOW_API_KEY_SHA256');
